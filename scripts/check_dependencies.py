#!/usr/bin/env python3
"""Report pinned vs upstream versions of external dependencies.

Pinned values live in bitstream-inspector/ci/deps.env. The weekly workflow
runs this script and opens/updates a tracking issue when FFmpeg has a newer
stable release. Runner-provided tools (NSIS, mingw-w64, nasm, CMake) are
reported for visibility; they follow the pinned Ubuntu image.
"""
import argparse
import datetime
import os
import re
import subprocess
import sys

FFMPEG_TAG = re.compile(r"^n(\d+)\.(\d+)(?:\.(\d+))?$")
NSIS_TAG = re.compile(r"^v(\d)(\d{2})(\d)?$")


def run(cmd, timeout=60):
    proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                          text=True, timeout=timeout)
    if proc.returncode != 0:
        raise RuntimeError(f"{' '.join(cmd)}: {proc.stderr.strip()}")
    return proc.stdout


def read_env(path):
    values = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, value = line.split("=", 1)
            values[key.strip()] = value.strip()
    return values


def version_tuple(text):
    parts = [int(p) for p in text.split(".")]
    while len(parts) < 3:
        parts.append(0)
    return tuple(parts)


def remote_tags(url):
    out = run(["git", "ls-remote", "--tags", "--refs", url], timeout=120)
    tags = []
    for line in out.splitlines():
        ref = line.split("refs/tags/", 1)[-1]
        if ref and not ref.endswith("^{}"):
            tags.append(ref)
    return tags


def latest_ffmpeg():
    found = []
    for tag in remote_tags("https://github.com/FFmpeg/FFmpeg"):
        m = FFMPEG_TAG.match(tag)
        if m:
            found.append((version_tuple(".".join(p for p in m.groups() if p)),
                          tag))
    return max(found) if found else (None, None)


def latest_nsis():
    found = []
    for tag in remote_tags("https://github.com/kichik/nsis"):
        m = NSIS_TAG.match(tag)
        if m:
            version = f"{m.group(1)}.{m.group(2)}"
            if m.group(3):
                version += "." + m.group(3)
            found.append((version_tuple(version), version, tag))
    return max(found) if found else (None, None, None)


def first_line(cmd):
    try:
        return run(cmd, timeout=20).splitlines()[0].strip()
    except (OSError, RuntimeError, subprocess.TimeoutExpired):
        return "not available"


def runner_nsis():
    try:
        out = run(["apt-cache", "policy", "nsis"], timeout=20)
    except (OSError, RuntimeError, subprocess.TimeoutExpired):
        return "not available"
    for line in out.splitlines():
        if line.strip().startswith("Candidate:"):
            return line.split(":", 1)[1].strip()
    return "not available"


def os_name():
    try:
        with open("/etc/os-release", encoding="utf-8") as f:
            for line in f:
                if line.startswith("PRETTY_NAME="):
                    return line.split("=", 1)[1].strip().strip('"')
    except OSError:
        pass
    return "unknown"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--output", help="write the Markdown report here")
    ap.add_argument("--github-output", help="write step outputs here")
    args = ap.parse_args()

    root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    env_path = os.path.join(root, "bitstream-inspector", "ci", "deps.env")
    deps = read_env(env_path)
    pinned = deps.get("FFMPEG_VERSION", "unknown")
    pinned_sha = deps.get("FFMPEG_SHA256", "unknown")

    try:
        ffmpeg_tuple, ffmpeg_tag = latest_ffmpeg()
        nsis_tuple, nsis_version, nsis_tag = latest_nsis()
    except (OSError, RuntimeError, subprocess.TimeoutExpired) as error:
        sys.stderr.write(f"error: {error}\n")
        return 1

    ffmpeg_update = (ffmpeg_tuple is not None and pinned != "unknown" and
                     ffmpeg_tuple > version_tuple(pinned))
    latest_ffmpeg_text = ffmpeg_tag or "unknown"

    runner_nsis_v = runner_nsis()
    nsis_newer = False
    if nsis_tuple is not None and re.match(r"^\d+\.\d+", runner_nsis_v):
        runner_tuple = version_tuple(runner_nsis_v.split("-")[0])
        nsis_newer = nsis_tuple > runner_tuple

    now = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d")
    lines = [
        "# Dependency report",
        "",
        f"Generated by `scripts/check_dependencies.py` on {now}.",
        "",
        "| Dependency | Current | Upstream latest | Status |",
        "|---|---|---|---|",
        f"| FFmpeg (bundled, Windows) | {pinned} | {latest_ffmpeg_text} | "
        f"{'**update available**' if ffmpeg_update else 'current'} |",
        f"| NSIS (installer toolchain) | {runner_nsis_v} (runner) | "
        f"{nsis_tag or 'unknown'} | "
        f"{'newer upstream (informational)' if nsis_newer else 'current'} |",
        f"| FFmpeg (Linux tests, linked) | {pinned} (pinned host build) | "
        f"{latest_ffmpeg_text} | "
        f"{'**update available**' if ffmpeg_update else 'current'} |",
        f"| FFmpeg (runner CLI) | {first_line(['ffmpeg', '-version'])} | "
        f"{latest_ffmpeg_text} | informational |",
        f"| mingw-w64 GCC | {first_line(['x86_64-w64-mingw32-gcc', '--version'])} | "
        f"runner image | informational |",
        f"| nasm | {first_line(['nasm', '-v'])} | runner image | informational |",
        f"| CMake | {first_line(['cmake', '--version'])} | runner image | "
        f"informational |",
        "",
        "Runner-provided tools follow the pinned `ubuntu-24.04` image; only the",
        "bundled FFmpeg version and its SHA-256 are pinned in",
        "`bitstream-inspector/ci/deps.env`.",
        "",
        f"Pinned FFmpeg SHA-256: `{pinned_sha}`",
        "",
    ]
    if ffmpeg_update:
        lines += [
            "## FFmpeg upgrade checklist",
            "",
            "- [ ] update `FFMPEG_VERSION` / `FFMPEG_SHA256` in "
            "`bitstream-inspector/ci/deps.env`",
            "- [ ] update DLL names in `installer/bitstream-inspector.nsi`, "
            "`installer/build_installer.sh`, `ci/ffmpeg.sh` and the READMEs",
            "- [ ] rebuild `third_party/ffmpeg-win64` and update "
            "`BUILD-INFO.txt` / `BUILD-INFO.zh-CN.txt`",
            "- [ ] run `ci/linux.sh release`, `ci/linux.sh asan` and "
            "`ci/windows.sh`",
            "- [ ] bump the tool version, changelog and bilingual release notes",
            "",
        ]
    report = "\n".join(lines)

    if args.output:
        with open(args.output, "w", encoding="utf-8") as f:
            f.write(report + "\n")
    else:
        print(report)

    if args.github_output:
        with open(args.github_output, "a", encoding="utf-8") as f:
            f.write(f"update_available={'true' if ffmpeg_update else 'false'}\n")
            f.write(f"pinned_ffmpeg={pinned}\n")
            f.write(f"latest_ffmpeg={latest_ffmpeg_text}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
